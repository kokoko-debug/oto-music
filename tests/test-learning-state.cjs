const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=require('./source.cjs');
const start=source.indexOf(' const ui=');
const end=source.indexOf(' restore(saved);',start)+' restore(saved);'.length;
const restore=source.slice(start,end);
function run(saved){const context={saved};vm.runInNewContext(restore+';this.result=JSON.stringify(ui);',context);return JSON.parse(context.result);}
const legacy=run({mode:'basics',page:'chord',step:2,selected:0,checked:true});
